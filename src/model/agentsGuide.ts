import type { ProjectConfig } from '../types';

const MEANINGS: Record<string, string> = {
	inbox: 'Captured, not yet looked at.',
	backlog: 'Understood, not chosen.',
	next: 'Chosen to be done soon. The pull list.',
	doing: 'In progress.',
	pr: 'A pull request is open.',
	merged: 'Landed on the main branch, not yet in a release.',
	released: 'Shipped in a release.',
	done: 'Finished.',
	canceled: 'Will not be done.',
};

function code(text: string): string {
	return `\`${text}\``;
}

function statusTable(config: ProjectConfig): string {
	const rows = config.statuses.map((status) => {
		const closed = config.statusesClosed.includes(status) ? 'closed' : 'open';
		return `| ${code(status)} | ${closed} | ${config.statusMeanings[status] ?? MEANINGS[status] ?? ''} |`;
	});
	return ['| Status | Kind | Meaning |', '|---|---|---|', ...rows].join('\n');
}

/**
 * The AGENTS.md body for one project: the file-editing contract, specialised with the project's
 * key, statuses and folders so that an agent landing in the folder needs nothing else.
 */
export function renderAgentsGuide(config: ProjectConfig, pluginVersion: string): string {
	const key = config.key;
	const projectNote = `${config.folder === '' ? '' : `${config.folder}/`}${config.name}.md`;
	const example = `${key}-123`;
	const releaseExample = `${key}-1.5.0`;
	const openStatus = config.statuses.find((s) => !config.statusesClosed.includes(s)) ?? config.statuses[0] ?? 'backlog';
	const r = config.releases;

	const whereLines = [
		`- Project note: ${code(projectNote)} (key ${code(key)}). Its frontmatter is the configuration this file was rendered from.`,
		`- Issues: ${code(`${config.issuesFolder}/`)}, one note per issue, file name ${code(`${key}-<number>.md`)}.`,
		r ? `- Releases: ${code(`${config.releasesFolder}/`)}, one note per version, file name ${code(`${key}-<version>.md`)}.` : null,
		`- Attachments: ${code(`${config.issuesFolder}/Attachments/`)}, embedded from issue bodies with ${code('![[file]]')}.`,
		config.issueTemplate ? `- Body template for new issues: ${code(config.issueTemplate)}.` : null,
	].filter((l): l is string => l !== null);

	const sections: string[] = [];

	sections.push(`# Working with ${config.name} issues

Generated by the Issues plugin ${pluginVersion} from the project note. The plugin rewrites this file whenever the project's configuration or the plugin changes, so edits here are lost; project-specific guidance belongs in the project note's body.

Issues are plain Markdown notes with YAML frontmatter. The Issues plugin renders them as a list and writes the same frontmatter you write by hand. Reordering rows is the one thing that has no file-level form: it is done in the plugin, by drag or the row menu.

## Where things are

${whereLines.join('\n')}

## Statuses, in order

${statusTable(config)}
${
	r
		? `
Releases are on. ${code(config.statusReleased)} ties an issue to a release note; shipping a release sweeps every issue in ${code(config.statusShipFrom)} into it. Issues in a closed status other than ${code(config.statusReleased)} disappear from the list ${config.hideClosedAfterDays} days after closing (they are not deleted).`
		: `
Releases are off for this project. Issues in a closed status disappear from the list ${config.hideClosedAfterDays} days after closing (they are not deleted).`
}

## Create an issue

1. List the files in ${code(`${config.issuesFolder}/`)}, take the highest ${code(`${key}-n`)} number and add one. Create the folder if it does not exist.
2. Create ${code(`${config.issuesFolder}/${key}-<n>.md`)}. If the path already exists, you raced another writer: recompute and retry.

\`\`\`markdown
---
title: Fix timer drift on iOS
project: ${key}
type: task
status: ${openStatus}
priority: medium
labels: []
created: YYYY-MM-DD
---
What is wrong or wanted, how to reproduce for a bug, and what done looks like.
\`\`\`

Rules for the frontmatter:

- Write ${code('title')}, ${code('project')}, ${code('type')}, ${code('status')}, ${code('priority')}, ${code('labels')}, ${code('created')}. This is what the plugin itself writes, minus ${code('order')}.
- ${code('project')} is ${code(key)}, verbatim.
- ${code('type')} is ${code('task')} or ${code('bug')}.
- ${code('status')} is one of the statuses above.${config.statuses.includes('inbox') ? ` Use ${code('inbox')} for something captured but not understood, ${code('backlog')} for understood work, or go straight to ${code('doing')} when starting on it.` : ''}
- ${code('priority')} is ${code('high')}, ${code('medium')} or ${code('low')}.
- ${code('created')} is today as ${code('YYYY-MM-DD')}.
- ${code('parent')}, when used, is a quoted wikilink to another issue in this project: ${code(`parent: "[[${key}-100]]"`)}.
- **Do not write ${code('order')}.** The plugin owns it. An issue without ${code('order')} sorts after every ordered row in its section, which is where fresh work belongs.
- Do not write ${code('closed')}${r ? ` or ${code('release')}` : ''} on creation unless the status requires them (see the status rules).${config.issueTemplate ? ` Copy the body of ${code(config.issueTemplate)} as the starting body.` : ''}

The body is Markdown. Keep it short; the title carries the row. Attach files by pasting them into the note in Obsidian, or by placing them in ${code(`${config.issuesFolder}/Attachments/`)} and embedding them with ${code('![[file]]')}.

## Change status

Set ${code('status')} to another value from the table, **remove ${code('order')}** so the issue lands at the bottom of its target section, and apply these rules. "Closed" means ${config.statusesClosed.map(code).join(', ')}.

| Transition | Also do |
|---|---|
| Open → closed | Set ${code('closed')} to today (${code('YYYY-MM-DD')}). |
| Closed → closed | Keep ${code('closed')}. |
| Closed → open | Remove ${code('closed')}. |${
		r
			? `
| Into ${code(config.statusReleased)} | Also set ${code('release')} to a quoted wikilink to the release note, ${code(`release: "[[${releaseExample}]]"`)}. Use this for a single issue that went out on its own, for instance in a hotfix. When a whole version went out, ship the release (below) so the release note and all ${code(config.statusShipFrom)} issues change together. |
| Out of ${code(config.statusReleased)} | Also remove ${code('release')}. |`
			: ''
	}

An agent may drive an issue through the whole cycle, forwards and backwards. Moving an issue to ${code('canceled')} with ${code('closed')} set is how an invalid issue is retired; nothing is deleted.

## Edit an issue

- Change ${code('title')}, ${code('type')}, ${code('priority')}, ${code('labels')}, ${code('parent')} and the body freely.
- Never rename the file, change ${code('project')}, or write ${code('order')}.
- Append to the body rather than rewriting it when adding progress notes. A dated heading (${code('## YYYY-MM-DD')}) is enough.
- Use the issue key (${code(example)}) in commit messages and branch names; that is the only cross-reference that exists.`);

	if (r) {
		sections.push(`## Releases

Release notes live in ${code(`${config.releasesFolder}/`)}, one per version, named ${code(`${key}-<version>.md`)}. The key prefix keeps wikilinks unique across projects.

### Plan a release

Create ${code(`${config.releasesFolder}/${releaseExample}.md`)} (creating the folder if needed):

\`\`\`markdown
---
type: release
project: ${key}
version: 1.5.0
status: planned
---
\`\`\`

The body is free Markdown for release notes and may stay empty.

### Ship a release

This is what the plugin's Ship button does. Do it after the build is live, in this order:

1. On the release note: set ${code('status: released')} and ${code('released')} to today. Create the note in that state if no planned note exists.
2. For every issue of this project whose ${code('status')} is ${code(config.statusShipFrom)}: set ${code('status')} to ${code(config.statusReleased)}, ${code('release')} to ${code(`"[[${key}-<version>]]"`)}, ${code('closed')} to today, and remove ${code('order')}.

If some ${code(config.statusShipFrom)} issues must stay out of the release, move them to another status first. If step 2 is interrupted, run it again: the issues still in ${code(config.statusShipFrom)} are exactly the unshipped ones.

### Changelog text

\`\`\`
- <title of task 1>
- <title of task 2>
Fixes
- <title of bug 1>
\`\`\`

Tasks first, then bugs under a ${code('Fixes')} line that is omitted when there are no bugs; within each group, issues with ${code('order')} ascending, then those without by ${code('created')} ascending. The plugin's "Copy changelog" produces exactly this.

### Undo a release

Set the release note back to ${code('status: planned')} and remove ${code('released')}; on each issue whose ${code('release')} names that note, set ${code('status')} to ${code(config.statusShipFrom)} and remove ${code('release')}, ${code('closed')} and ${code('order')}.`);
	}

	sections.push(`## What breaks the list

- A duplicate key, from not recomputing the number after a collision.
- A ${code('status')} value that is not in the table. The issue lands in an extra section headed by that value until fixed.
- A hand-written ${code('order')}. The row lands at an arbitrary position in its section.
- ${code('closed')} present on an open issue, or missing on a closed one.${
		r ? `\n- A released issue without ${code('release')}, or a release note marked ${code('released')} while its issues still sit in ${code(config.statusShipFrom)}. Ship both sides together.` : ''
	}
- Unquoted wikilinks in ${code('parent')}${r ? ` or ${code('release')}` : ''}. YAML needs ${code(`"[[${key}-100]]"`)}.
- Dates in any format other than ${code('YYYY-MM-DD')}.${r ? `\n- A release note named without the key prefix. ${code('[[1.5.0]]')} is ambiguous across projects.` : ''}

Direct file edits are picked up by Obsidian within a second, including through Obsidian Sync from another device. When Obsidian is running on this machine, its command-line interface can create files and set properties through the app instead; the rules above are the same either way.`);

	return `${sections.join('\n\n')}\n`;
}
